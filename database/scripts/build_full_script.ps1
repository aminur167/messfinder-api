<#
    build_full_script.ps1
    Joins every .sql file of the database folder, in the right order, into ONE file:
        database/build/mess_finder_full.sql
    Open that file in MySQL Workbench and press the lightning button to build everything at once.

    Run it again whenever you change any .sql file:
        powershell -ExecutionPolicy Bypass -File .\scripts\build_full_script.ps1
#>

$databaseFolder = Split-Path -Parent $PSScriptRoot
$outputFile     = Join-Path $databaseFolder 'build\mess_finder_full.sql'

# Folders are read in this order. The seed data comes BEFORE the triggers and events,
# so the demo data is loaded as it is and no trigger adds anything on top of it.
# The security folder is left out on purpose: it creates MySQL users, run it yourself.
$folderOrder = @('schema', 'seed', 'views', 'functions', 'procedures', 'indexes', 'triggers', 'events')

$text = New-Object System.Text.StringBuilder
[void]$text.AppendLine('-- ====================================================================')
[void]$text.AppendLine('-- Mess Finder: complete database in one file')
[void]$text.AppendLine('-- This file is generated by scripts/build_full_script.ps1. Do not edit it by hand,')
[void]$text.AppendLine('-- change the small files in the other folders and build again.')
[void]$text.AppendLine('-- ====================================================================')
[void]$text.AppendLine('')

$fileCount = 0
foreach ($folder in $folderOrder) {
    $folderPath = Join-Path $databaseFolder $folder
    if (-not (Test-Path $folderPath)) { continue }

    $files = Get-ChildItem -Path $folderPath -Filter '*.sql' | Sort-Object Name
    foreach ($file in $files) {
        [void]$text.AppendLine('')
        [void]$text.AppendLine("-- >>>>>>>>>> $folder/$($file.Name)")
        [void]$text.AppendLine([System.IO.File]::ReadAllText($file.FullName))
        $fileCount++
    }
}

# Write as UTF-8 without BOM so MySQL reads Bangla text correctly.
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($outputFile, $text.ToString(), $utf8NoBom)

Write-Host "Joined $fileCount files into $outputFile"
